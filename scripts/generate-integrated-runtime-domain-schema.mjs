#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";

import { integratedRuntimeSchemaFingerprint } from "./verify-integrated-runtime-schema-convergence.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const manifestPath = path.join(root, "engine/schema/integrated-runtime-r5-r9.v1.json");
const typescriptPath = path.join(root, "app/game/rust-integrated-runtime-domain-schema.generated.ts");
const rustPath = path.join(root, "engine/crates/blockwild-engine/src/runtime_domain_schema_generated.rs");
const check = process.argv.includes("--check");

function assert(condition, message) {
  if (!condition) throw new Error(message);
}

function constantName(id) {
  return id.replaceAll(/[^a-zA-Z0-9]+/gu, "_").replaceAll(/^_+|_+$/gu, "").toUpperCase();
}

function quote(value) {
  return JSON.stringify(value);
}

function readManifest() {
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  assert(manifest?.schemaVersion === 1, "integrated runtime domain schema manifest is not v1");
  assert(/^[0-9a-f]{64}$/u.test(manifest?.fingerprint?.value), "integrated runtime domain schema fingerprint is not sealed");
  assert(
    manifest.fingerprint.value === integratedRuntimeSchemaFingerprint(manifest),
    "integrated runtime domain schema fingerprint has drifted",
  );
  assert(Array.isArray(manifest.domains) && manifest.domains.length === 5, "integrated runtime domain schema does not contain R5-R9");
  const families = [];
  for (const row of manifest.domains) {
    for (const direction of ["requests", "receipts"]) {
      assert(Array.isArray(row?.families?.[direction]), `${row?.phase}/${row?.domain} ${direction} are missing`);
      for (const family of row.families[direction]) {
        assert(typeof family?.id === "string" && /^[a-z0-9][a-z0-9.-]*$/u.test(family.id), "wire family id is invalid");
        assert(family.direction === (direction === "requests" ? "request" : "receipt"), `${family.id} direction is invalid`);
        assert(typeof family.magic === "string" && /^[A-Z0-9]{4}$/u.test(family.magic), `${family.id} magic is invalid`);
        assert(typeof family.typeId === "string" && family.typeId.startsWith("blockwild."), `${family.id} type id is invalid`);
        assert(Number.isInteger(family.operationSchema) && family.operationSchema > 0 && family.operationSchema <= 0xffff,
          `${family.id} operation schema is invalid`);
        assert(Number.isInteger(family.innerSchema) && family.innerSchema > 0 && family.innerSchema <= 0xffff,
          `${family.id} inner schema is invalid`);
        assert(typeof family.normalPath === "boolean", `${family.id} normal-path flag is invalid`);
        families.push(Object.freeze({
          phase: row.phase,
          domain: row.domain,
          ...family,
        }));
      }
    }
  }
  assert(new Set(families.map(({ id }) => id)).size === families.length, "wire family ids are not unique");
  return { manifest, families };
}

function renderTypescript(manifest, families) {
  const entries = families.map((family) => `  ${quote(family.id)}: Object.freeze({\n${[
    ["phase", family.phase],
    ["domain", family.domain],
    ["direction", family.direction],
    ["magic", family.magic],
    ["typeId", family.typeId],
    ["operationSchema", family.operationSchema],
    ["innerSchema", family.innerSchema],
    ["normalPath", family.normalPath],
  ].map(([key, value]) => `    ${key}: ${typeof value === "string" ? quote(value) : String(value)},`).join("\n")}\n  }),`).join("\n");
  return `// @generated by scripts/generate-integrated-runtime-domain-schema.mjs\n// Source: engine/schema/integrated-runtime-r5-r9.v1.json\n// Do not edit by hand.\n\nexport const RUST_INTEGRATED_RUNTIME_DOMAIN_SCHEMA_FINGERPRINT_V1 = ${quote(manifest.fingerprint.value)} as const;\nexport const RUST_INTEGRATED_RUNTIME_DOMAIN_WIRE_VERSION_V1 = ${manifest.protocol.wireVersion} as const;\nexport const RUST_INTEGRATED_RUNTIME_SCHEMA_VERSION_V1 = ${manifest.protocol.runtimeSchema} as const;\n\nexport const RUST_INTEGRATED_RUNTIME_DOMAIN_WIRE_FAMILIES_V1 = Object.freeze({\n${entries}\n} as const);\n\nexport type RustIntegratedRuntimeDomainWireFamilyIdV1 =\n  keyof typeof RUST_INTEGRATED_RUNTIME_DOMAIN_WIRE_FAMILIES_V1;\n\nexport function rustIntegratedRuntimeDomainWireFamilyV1<\n  Id extends RustIntegratedRuntimeDomainWireFamilyIdV1,\n>(id: Id): (typeof RUST_INTEGRATED_RUNTIME_DOMAIN_WIRE_FAMILIES_V1)[Id] {\n  return RUST_INTEGRATED_RUNTIME_DOMAIN_WIRE_FAMILIES_V1[id];\n}\n`;
}

function renderRust(manifest, families) {
  const constants = families.map((family) => {
    const name = constantName(family.id);
    return `pub const ${name}_MAGIC: [u8; 4] = *b${quote(family.magic)};\npub const ${name}_TYPE_ID: &str = ${quote(family.typeId)};\npub const ${name}_OPERATION_SCHEMA: u16 = ${family.operationSchema};\npub const ${name}_INNER_SCHEMA: u16 = ${family.innerSchema};`;
  }).join("\n\n");
  const entries = families.map((family) => `    IntegratedRuntimeDomainWireFamilyV1 {\n        phase: ${quote(family.phase)},\n        domain: ${quote(family.domain)},\n        id: ${quote(family.id)},\n        direction: ${quote(family.direction)},\n        magic: *b${quote(family.magic)},\n        type_id: ${quote(family.typeId)},\n        operation_schema: ${family.operationSchema},\n        inner_schema: ${family.innerSchema},\n        normal_path: ${family.normalPath},\n    },`).join("\n");
  return `// @generated by scripts/generate-integrated-runtime-domain-schema.mjs
// Source: engine/schema/integrated-runtime-r5-r9.v1.json
// Do not edit by hand.

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct IntegratedRuntimeDomainWireFamilyV1 {
    pub phase: &'static str,
    pub domain: &'static str,
    pub id: &'static str,
    pub direction: &'static str,
    pub magic: [u8; 4],
    pub type_id: &'static str,
    pub operation_schema: u16,
    pub inner_schema: u16,
    pub normal_path: bool,
}

pub const INTEGRATED_RUNTIME_DOMAIN_SCHEMA_FINGERPRINT_V1: &str = ${quote(manifest.fingerprint.value)};
pub const INTEGRATED_RUNTIME_DOMAIN_WIRE_VERSION_V1: u16 = ${manifest.protocol.wireVersion};
pub const INTEGRATED_RUNTIME_SCHEMA_VERSION_V1: u16 = ${manifest.protocol.runtimeSchema};

${constants}

pub const INTEGRATED_RUNTIME_DOMAIN_WIRE_FAMILIES_V1: &[IntegratedRuntimeDomainWireFamilyV1] = &[
${entries}
];

#[cfg(test)]
mod tests {
    use std::collections::BTreeSet;

    use super::*;

    #[test]
    fn generated_registry_is_closed_unique_and_normal_path_explicit() {
        let mut ids = BTreeSet::new();
        let mut domains = BTreeSet::new();
        for family in INTEGRATED_RUNTIME_DOMAIN_WIRE_FAMILIES_V1 {
            assert!(ids.insert(family.id), "duplicate generated family {}", family.id);
            domains.insert((family.phase, family.domain));
            assert_eq!(family.magic.len(), 4);
            assert!(family.type_id.starts_with("blockwild."));
            assert!(family.operation_schema > 0);
            assert!(family.inner_schema > 0);
        }
        assert_eq!(
            domains,
            BTreeSet::from([
                ("R5", "simulation"),
                ("R6", "entities"),
                ("R7", "gameplay"),
                ("R8", "persistence"),
                ("R9", "network"),
            ])
        );
    }
}
`;
}

function formatRust(source) {
  const result = spawnSync("rustfmt", ["--edition", "2024", "--emit", "stdout"], {
    cwd: path.join(root, "engine"),
    input: source,
    encoding: "utf8",
    windowsHide: true,
  });
  if (result.error || result.status !== 0) {
    throw new Error(`rustfmt failed for generated schema: ${result.error?.message ?? result.stderr ?? `exit ${result.status}`}`);
  }
  return result.stdout;
}

function update(target, expected) {
  if (check) {
    let actual;
    try { actual = readFileSync(target, "utf8"); }
    catch { throw new Error(`generated integrated runtime domain schema is missing: ${path.relative(root, target)}`); }
    if (actual !== expected) throw new Error(`generated integrated runtime domain schema is stale: ${path.relative(root, target)}`);
    return;
  }
  writeFileSync(target, expected, "utf8");
}

const { manifest, families } = readManifest();
update(typescriptPath, renderTypescript(manifest, families));
update(rustPath, formatRust(renderRust(manifest, families)));
process.stdout.write(`integrated-runtime-domain-schema=${check ? "ok" : "written"} families=${families.length} fingerprint=${manifest.fingerprint.value}\n`);
