const block = (
  id: BlockId,
  name: string,
  top: number,
  side: number,
  bottom: number,
  hardness: number,
  color: string,
  preferredTool: BlockTool,
  requiredTier = 0,
  extras: Partial<BlockDefinition> = {},
): BlockDefinition => {
  const solid = extras.solid ?? true;
  const layer = extras.layer ?? "opaque";
  const fullCube = !extras.shape || extras.shape === "cube";
  const lightDampening = extras.lightDampening
    ?? (id === BlockId.Air ? 0
      : extras.liquid === "water" || extras.waterlogged ? 1
        : layer === "transparent" ? 0
          : layer === "cutout" ? 1
            : solid && fullCube ? 15 : 0);
  return {
    id,
    name,
    top,
    side,
    bottom,
    hardness,
    color,
    preferredTool,
    requiredTier,
    solid,
    layer,
    lightDampening,
    emissiveStrength: layer === "emissive" ? 0.72 : 0,
    ...extras,
  };
};

